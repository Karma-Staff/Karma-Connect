// Bundle the AI pipeline in src/lib (ES modules, written for the browser) into one CommonJS file
// the server can require: server/gen/prep.cjs. Run by `npm run build`, so Render builds it on
// every deploy. The server uses it to research a new LinkedIn connection by itself
// (server/li-prep.cjs); without the file it simply leaves that to the Send Queue in the browser.
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
await build({
  entryPoints: [path.join(root, "src/lib/prep.js")],
  outfile: path.join(root, "server/gen/prep.cjs"),
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node20",
  logLevel: "warning",
  banner: { js: "// GENERATED by scripts/build-server-lib.mjs from src/lib/prep.js — do not edit." },
});
console.log("server/gen/prep.cjs built");
